#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");
const migrationsDir = path.join(rootDir, "supabase", "migrations");
const outputPath = path.join(rootDir, "supabase", "functions", "_shared", "index-bootstrap-sql.ts");
const MAX_BOOTSTRAP_MIGRATION_PREFIX = 43;

if (!fs.existsSync(migrationsDir)) {
  if (fs.existsSync(outputPath)) {
    console.log(
      [
        "Skipping index bootstrap SQL generation.",
        "supabase/migrations is not present in this repo, so the existing",
        path.relative(rootDir, outputPath),
        "file will be kept.",
      ].join(" "),
    );
    process.exit(0);
  }

  console.error(
    [
      "Cannot generate index bootstrap SQL because supabase/migrations is missing",
      "and no existing generated bootstrap file was found at",
      path.relative(rootDir, outputPath) + ".",
    ].join(" "),
  );
  process.exit(1);
}

const migrationFiles = fs
  .readdirSync(migrationsDir)
  .filter((entry) => entry.endsWith(".sql"))
  .map((entry) => {
    const prefix = Number.parseInt(entry.slice(0, 4), 10);
    return {
      entry,
      prefix: Number.isFinite(prefix) ? prefix : 0
    };
  })
  .filter(({ prefix }) => prefix > 0 && prefix <= MAX_BOOTSTRAP_MIGRATION_PREFIX)
  .sort((left, right) => left.entry.localeCompare(right.entry));

const sql = migrationFiles
  .map(({ entry }) => {
    const contents = fs.readFileSync(path.join(migrationsDir, entry), "utf8").trim();
    return `-- ${entry}\n${contents}`;
  })
  .join("\n\n");

const output = [
  "// Auto-generated by scripts/generate-index-bootstrap-sql.mjs",
  "// Do not edit by hand.",
  "",
  `export const indexBootstrapSql = ${JSON.stringify(`${sql}\n`)};`,
  ""
].join("\n");

fs.writeFileSync(outputPath, output, "utf8");
console.log(
  `Bundled ${migrationFiles.length} migration files into ${path.relative(rootDir, outputPath)}`
);
